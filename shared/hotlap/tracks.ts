/**
 * The Hotlap campaign. Array order IS the campaign order (3 easy, 3 medium,
 * 3 hard, 3 expert). Every track here is ORIGINAL (designed for this
 * project) — never recreate or name-check another game's tracks.
 *
 * Authoring cheatsheet (see track.ts for the full model):
 *   { k: "s", len }            straight, metres
 *   { k: "t", deg, r }         arc: deg > 0 = LEFT, < 0 = RIGHT; r = radius (m)
 *   rise                       height change across the segment (m)
 *   bank                       bank (deg) reached at segment END, + = left edge up
 *                              (bank a RIGHT turn with +, a LEFT turn with -).
 *                              It ramps across the whole segment, so for a turn
 *                              that is banked throughout, split it: a short
 *                              entry arc with the bank, the main arc, then a
 *                              short exit arc with bank: 0.
 *   width, walls, cp, boost, gap
 *   theme                      "dawn" | "noon" | "dusk" | "night" | "neon" | "storm"
 *
 * Design notes learned the hard way:
 *   - A convex vertical change launches the car (curvature ~ 6*rise/len^2 for
 *     a hump between flat pieces). Keep fast crests away from corners.
 *   - The validation bot commits to >= 60 m/s within 160 m of a gap, so give
 *     every jump a straight run-up and a long landing before the next corner.
 *   - Roads may cross only as clean bridges (>= 9 m vertical separation).
 *
 * `npx tsx tools/hotlap-tracks.ts [trackId]` validates every track (overlap,
 * both bots, determinism) and prints calibrated medal lines to paste here.
 * Bump a track's `version` whenever its geometry changes.
 */
