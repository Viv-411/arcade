/**
 * The Hotlap campaign. Array order IS the campaign order (3 easy, 3 medium,
 * 3 hard, 3 expert). Every track here is ORIGINAL (designed for this
 * project) — never recreate or name-check another game's tracks.
 *
 * House style (owner feedback, 2026-10-27): compact, dense and technical.
 * Mostly tight 90s (r 10–20 m) and hairpins (r 12–16 m) joined by short
 * 30–120 m straights, one or two 150–250 m blasts per track, small kickers
 * and step-down jumps, climbs, bridges. NO boost pads (owner request).
 * Laps (BOT_CAREFUL): easy ~18–30 s, medium ~25–40, hard ~30–45, expert ~35–55.
 *
 * Authoring cheatsheet (see track.ts for the full model):
 *   { k: "s", len }            straight, metres
 *   { k: "t", deg, r }         arc: deg > 0 = LEFT, < 0 = RIGHT; r = radius (m)
 *   rise                       height change across the segment (m)
 *   bank                       bank (deg) reached at segment END, + = left edge up
 *                              (bank a RIGHT turn with +, a LEFT turn with -).
 *                              It ramps across the whole segment, so for a turn
 *                              that is banked throughout, split it: a short
 *                              entry arc with the bank, the main arc, then a
 *                              short exit arc with bank: 0.
 *   width, walls, cp, gap      (`boost` exists in the engine; the campaign
 *                              doesn't use it)
 *   theme                      "dawn" | "noon" | "dusk" | "night" | "neon" | "storm"
 *
 * Design notes learned the hard way:
 *   - A convex vertical change launches the car (curvature ~ 6*rise/len^2 for
 *     a hump between flat pieces). Never end a fast straight climb right
 *     before a corner: either finish the climb INSIDE a slow corner (rise on
 *     the arc), or spread it over several rising pieces (consecutive rises
 *     blend smoothly) and leave >= 40 m of flat before the turn.
 *   - Every segment with a rise between two flat pieces is an S-curve (zero
 *     slope at both ends). The piece before a gap launches at 1.5x its slope.
 *   - Jumps: straight run-up, then a landing long enough to brake for the
 *     next corner even at a strong player's takeoff speed (~60–80 m). A flat
 *     lip clears a gap of G metres dropping D metres at v >= G*sqrt(g/(2D))
 *     (g = 15.5) — keep that well below what a hesitant player carries.
 *   - Roads may cross only as clean bridges (>= 9 m vertical separation).
 *     Hairpin legs sit 2r apart, so 2r must be >= width + 8 (r 12 at w 12).
 *     Stacked laps (Stepwell) must drop >= 9 m per lap, and checkpoints must
 *     be less than a lap apart so falling to the lap below skips a gate.
 *   - Wall-less sections: put them where falling off only drops you onto an
 *     EARLIER part of the road (never a shortcut), and wall the first corner
 *     after a long flat-out approach.
 *
 * `npx tsx tools/hotlap-tracks.ts [trackId]` validates every track (overlap,
 * both bots, determinism) and prints calibrated medal lines to paste here.
 * Bump a track's `version` whenever its geometry changes.
 */
